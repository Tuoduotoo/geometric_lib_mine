
def area(a, b): 
    '''
    Возращает площадь прямоугольника.
    Принимает a, b(длину и ширину), возвращает произведение a, b.
    '''
    return a * b 

def perimeter(a, b): 
    '''
    Возращает периметр прямоугольника.
    Принимает a, b(длину и ширину), возвращает удвоенную сумму a, b.
    '''
    return 2 * (a + b) 