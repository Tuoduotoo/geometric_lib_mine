
def area(a, h): 
    '''
    Возращает площадь треугольника.
    Принимает a(сторону), h(высоту), возвращает произведение a * h разделить на 2.
    '''
    return a * h / 2 

def perimeter(a, b, c): 
    '''
    Возращает периметр треугольника.
    Принимает a, b, c(стороны), возвращает сумму a, b, c.
    '''
    return a + b + c 