
def area(a, h): 
    """Вычисляет площадь треугольника через сторону и высоту.

    Площадь треугольника вычисляется как половина произведения
    стороны на высоту, проведённую к этой стороне:
    S = (a * h) / 2.

    Args:
        a (float): Длина стороны треугольника (основание).
        h (float): Высота, проведённая к этой стороне.

    Returns:
        float: Площадь треугольника.

    Example:
        >>> area(4, 3)
        6.0
        >>> area(10, 5)
        25.0
    """
    return a * h / 2 

def perimeter(a, b, c): 
    """Вычисляет периметр треугольника по трём сторонам.

    Периметр треугольника вычисляется как сумма длин всех
    его сторон: P = a + b + c.

    Args:
        a (float): Длина первой стороны.
        b (float): Длина второй стороны.
        c (float): Длина третьей стороны.

    Returns:
        float: Периметр треугольника.

    Example:
        >>> perimeter(3, 4, 5)
        12
        >>> perimeter(6, 6, 6)
        18
    """
    return a + b + c 