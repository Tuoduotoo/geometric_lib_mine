import math


def area(r):
    """Вычисляет площадь круга по его радиусу.

    Площадь круга вычисляется как π * r².

    Args:
        r (float): Радиус круга.

    Returns:
        float: Площадь круга.

    Example:
        >>> area(1)
        3.141592653589793
    """
    return math.pi * r * r


def perimeter(r):
    """Вычисляет длину окружности (периметр круга) по радиусу.

    Длина окружности вычисляется по формуле C = 2 * π * r.
    Функция принимает радиус и возвращает удвоенное
    произведение радиуса на число π.

    Args:
        r (float): Радиус круга, должен быть неотрицательным.

    Returns:
        float: Длина окружности, выраженная числом с плавающей точкой.

    Example:
        >>> perimeter(1)
        6.283185307179586
        >>> perimeter(2)
        12.566370614359172
    """
     
    return 2 * math.pi * r

