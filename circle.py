import math


def area(r):
    '''
    Возращает площадь круга.
    Принимает r(радиус), возвращает произведение квадрата r и pi.
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Возращает периметр круга.
    Принимает r(радиус), возвращает удвоенное произведение r и pi.
    '''
    return 2 * math.pi * r

