
def area(a):
    """Вычисляет площадь квадрата.

    Площадь квадрата вычисляется как квадрат длины его стороны:
    S = a². Функция принимает сторону и возвращает её произведение
    на саму себя.

    Args:
        a (float): Длина стороны квадрата.

    Returns:
        float: Площадь квадрата.

    Example:
        >>> area(2)
        4
        >>> area(5)
        25
    """
    return a * a


def perimeter(a):
    """Вычисляет периметр квадрата.

    Периметр квадрата вычисляется как произведение длины его
    стороны на 4: P = 4 * a. Функция принимает сторону и
    возвращает её учётверённое значение.

    Args:
        a (float): Длина стороны квадрата.

    Returns:
        float: Периметр квадрата.

    Example:
        >>> perimeter(2)
        8
        >>> perimeter(5)
        20
    """
    return 4 * a
